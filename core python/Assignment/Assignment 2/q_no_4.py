#WAP to calculate area of triangle and rectangle

lenght=int(input('enter a length:'))
breadth=int(input('enter a breadth:'))
base=int(input('enter a base:'))
height=int(input('enter a height:'))
area_of_triangle=1/2*base*height
area_of_rectangle=lenght*breadth
print(f'area of triangle {area_of_triangle},area of rectangle {area_of_rectangle}')